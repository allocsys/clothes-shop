export function generateStaticParams() {
  return Object.keys(pages).map((slug) => ({ slug }));
}

type Props = { params: Promise<{ slug: string }> };

export async function generateMetadata({ params }: Props): Promise<Metadata> {
  const { slug } = await params;
  const page = pages[slug];
  if (!page) return {};
  return { title: page.title, description: page.intro };
}

function ContactBlock() {
  const { phone, address } = site.contact;
  const socials = site.socials.filter((s) => s.href && s.href !== '#');
  const hasAny = !!phone || !!address || socials.length > 0;

  return (
    <section className='mt-8 rounded-3xl bg-surface p-6'>
      <h2 className='text-lg font-bold'>راه‌های ارتباطی</h2>
      {hasAny ? (
        <dl className='mt-4 space-y-3 text-sm leading-8'>
          {phone && (
            <div>
              <dt className='text-ink/70'>تلفن</dt>
              <dd className='font-bold'><a href={'tel:' + phone.replace(/\s/g, '')} dir='ltr' className='inline-block py-1'>{phone}</a></dd>
            </div>
          )}
          {address && (
            <div>
              <dt className='text-ink/70'>نشانی</dt>
              <dd className='font-bold'>{address}</dd>
            </div>
          )}
          {socials.length > 0 && (
            <div>
              <dt className='text-ink/70'>شبکه‌های اجتماعی</dt>
              <dd className='flex flex-wrap gap-2 pt-1'>
                {socials.map((s) => (
                  <a key={s.label} href={s.href} target='_blank' rel='noopener noreferrer' className='rounded-full border border-ink/15 px-4 py-2.5 text-sm font-bold'>{s.label}</a>
                ))}
              </dd>
            </div>
          )}
        </dl>
      ) : (
        <p className='mt-3 text-sm leading-8 text-ink/70'>راه‌های ارتباطی به‌زودی در همین صفحه اضافه می‌شود. تا آن زمان می‌توانید سفارش خود را از صفحه پیگیری سفارش دنبال کنید.</p>
      )}
      <Link href='/track' className='mt-4 inline-block rounded-full bg-brand px-5 py-2.5 text-sm font-bold text-white'>پیگیری سفارش</Link>
    </section>
  );
}

export default async function InfoPage({ params }: Props) {
  const { slug } = await params;
  const page = pages[slug];
  if (!page) notFound();

  return (
    <article className='mt-6 max-w-3xl'>
      <h1 className='mb-3 text-2xl font-bold'>{page.title}</h1>
      {page.intro && <p className='leading-8 text-ink/80'>{page.intro}</p>}

      {page.sections.map((s, i) => (
        <section key={i} className='mt-7'>
          {s.h && <h2 className='mb-2 text-lg font-bold'>{s.h}</h2>}
          {s.p?.map((t, j) => (
            <p key={j} className='mt-2 text-sm leading-8 text-ink/80'>{t}</p>
          ))}
          {s.list && (
            <ul className='mt-2 list-disc space-y-1 pr-5 text-sm leading-8 text-ink/80'>
              {s.list.map((t, j) => (
                <li key={j}>{t}</li>
              ))}
            </ul>
          )}
        </section>
      ))}

      {slug === 'contact-us' && <ContactBlock />}
    </article>
  );
}
